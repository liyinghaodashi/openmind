try {
  let checks = 0;
  const assert = (condition, message) => {checks++; if (!condition) throw new Error(message);};
  await toggleSettings(true);
  const key = $('setting-globalWakeShortcut');
  const row = key.closest('.setting-row');
  const buttons = [...row.querySelectorAll('.setting-shortcut-choices button')];
  const [save, clear] = row.querySelectorAll('.setting-shortcut-actions button');
  const current = row.querySelector('.setting-shortcut-current');
  const status = row.querySelector('.setting-shortcut-status');
  assert(row.closest('.settings-group').querySelector('h2').textContent === '通用设置', 'Shortcut must be in general settings');
  assert(current.textContent.includes('未设置'), 'Old settings must default to disabled');
  buttons[0].click();
  save.click();
  assert(status.textContent.includes('至少选择'), 'Unmodified keys must be rejected');
  buttons[0].click(); buttons[1].click(); key.value = 'F19'; save.click();
  assert(save.disabled, 'Save must prevent edits while registration is pending');
  await settings.flush();
  assert(window.__compactSettings.globalWakeShortcut === 'Ctrl+Alt+F19', 'Shortcut must persist');
  assert(current.textContent.includes('Ctrl + Option + F19') && !save.disabled && !status.textContent, 'Saved shortcut must display and controls recover');
  buttons[0].focus();
  buttons[0].dispatchEvent(new KeyboardEvent('keydown', {key: 'ArrowRight', bubbles: true, cancelable: true}));
  assert(document.activeElement === buttons[1], 'Arrow keys must navigate modifier buttons');
  const originalSave = native.SaveSettings;
  native.SaveSettings = async () => {throw new Error('模拟系统快捷键冲突');};
  key.value = 'F20'; save.click(); await settings.flush();
  assert(key.value === 'F19' && status.textContent.includes('模拟系统快捷键冲突'), 'Registration failure must roll back and show a local error');
  assert(window.__compactSettings.globalWakeShortcut === 'Ctrl+Alt+F19', 'Failure must preserve saved shortcut');
  native.SaveSettings = originalSave;
  clear.click(); await settings.flush();
  assert(window.__compactSettings.globalWakeShortcut === '' && current.textContent.includes('未设置'), 'Clear must persist disabled state');
  buttons[1].click(); key.value = 'KeyO'; save.click(); await settings.flush();
  assert(window.__compactSettings.globalWakeShortcut === 'Ctrl+Alt+KeyO', 'Letter shortcut must persist');
  row.scrollIntoView({block: 'center'});
  await window.__compactRequest({action: 'capture', name: 'global-shortcut.png'});
  await toggleSettings(false);
  document.dispatchEvent(new KeyboardEvent('keydown', {key: 'F12', bubbles: true, cancelable: true}));
  while (switchingSettings) await new Promise(resolve => setTimeout(resolve, 20));
  assert(!$('settings-page').hidden && key.value === 'KeyO', 'F12 must reopen settings with saved shortcut');
  native.GetGlobalShortcutStatus = async () => '全局快捷键未生效：模拟启动冲突';
  $('setting-mdCompactWindow').click(); await settings.flush();
  assert(status.textContent.includes('模拟启动冲突'), 'Startup conflict must remain visible after unrelated settings save');
  window.webkit.messageHandlers.result.postMessage({passed: true, message: `PASS: ${checks} global shortcut settings checks`});
} catch (error) {
  window.webkit.messageHandlers.result.postMessage({passed: false, message: error.stack || String(error)});
}
