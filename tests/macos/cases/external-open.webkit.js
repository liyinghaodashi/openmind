try{
  const assert=(value,message)=>{if(!value)throw new Error(message)};
  const fixture=window.__fileDragFixture;
  const assertOutline=()=>{
    assert(!$('sidebar').hidden&&!$('document-outline').hidden&&$('file-tree').hidden,'外部打开文件后没有显示大纲');
    assert($('sidebar-title').textContent==='大纲'&&$('toggle-outline').getAttribute('aria-pressed')==='true','大纲切换按钮状态不一致');
  };
  const waitFor=async predicate=>{for(let i=0;i<100&&!predicate();i++)await new Promise(resolve=>setTimeout(resolve,20));assert(predicate(),'等待打开文件超时')};
  await waitFor(()=>state.snapshot?.path==='源/笔记.md');
  assert(!$('markdown-page').hidden,'冷启动没有显示 Markdown 正文');
  assertOutline();
  const shown=fixture.calls.filter(call=>call[0]==='show-window');
  assert(shown.length===1,'启动完成后没有主动显示原生窗口');
  assert(shown[0][1]===false&&shown[0][2].includes('源/笔记.md'),'原生窗口显示时正文尚未就绪');
  assert(state.expanded.has('源'),'没有展开目标文件的父目录');
  const edited=state.snapshot.source+'\n切换前保存的编辑\n';
  enqueue('source',edited);
  fixture.pending.push('/fixture-only/源/子/想法.mind.md');
  fixture.listeners.get('document:open-requested')();
  await waitFor(()=>state.snapshot?.path==='源/子/想法.mind.md');
  assert(isMindMapPath(state.snapshot.path),'运行中打开未切换 mind 模式');
  assert(fixture.documents.get('源/笔记.md').source===edited,'切换前没有完成编辑保存');
  assert(fixture.calls.findIndex(call=>call[0]==='save')<fixture.calls.findIndex(call=>call[0]==='external-open'&&call[1]==='源/子/想法.mind.md'),'打开顺序早于保存完成');
  await waitFor(()=>!state.navigating);
  $('toggle-outline').click();
  $('toggle-sidebar').click();
  state.checking=true;
  fixture.pending.push('/fixture-only/根.md');fixture.listeners.get('document:open-requested')();
  await new Promise(resolve=>setTimeout(resolve,50));
  assert(state.snapshot.path==='源/子/想法.mind.md','后台检查期间发生了文档切换');
  state.checking=false;
  await waitFor(()=>state.snapshot?.path==='根.md');
  assertOutline();
  await waitFor(()=>!state.navigating);
  $('toggle-outline').click();
  fixture.pending.push('/other/目标/笔记.md');fixture.listeners.get('document:open-requested')();
  await waitFor(()=>state.workspace?.root==='/other'&&state.snapshot?.path==='目标/笔记.md');
  assert($('workspace-name').textContent==='其他目录','跨工作区打开没有更新目录');
  assertOutline();
  await waitFor(()=>!state.navigating);
  $('toggle-outline').click();
  const session=state.snapshot.session;
  fixture.pending.push('/other/不存在.md');fixture.listeners.get('document:open-requested')();
  await waitFor(()=>$('error-banner').textContent.includes('文件不存在'));
  assert(state.snapshot.session===session&&state.workspace.root==='/other','打开失败清空了原文档');
  assert(!$('file-tree').hidden&&$('document-outline').hidden,'打开失败改变了侧栏模式');
  state.blocked=true;
  fixture.pending.push('/other/根.md');fixture.listeners.get('document:open-requested')();
  await new Promise(resolve=>setTimeout(resolve,300));
  assert(state.snapshot.session===session,'写入被阻止时丢弃了当前文档');
  state.blocked=false;
  await waitFor(()=>state.snapshot?.path==='根.md');
  window.webkit.messageHandlers.result.postMessage({passed:true,message:'PASS: cold/warm opens, save-before-switch, busy request retention, workspace switch and failure preservation'});
}catch(error){window.webkit.messageHandlers.result.postMessage({passed:false,message:String(error.message)+'\n'+String(error.stack||error)})}
