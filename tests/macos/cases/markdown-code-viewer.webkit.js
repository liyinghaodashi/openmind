try{
  const source=['正文','','~~~js','const first = 1;','~~~','','~~~MeRmAiD','graph TD','A --> B','~~~'].join('\n');
  const options={session:'viewer',path:'代码.md',reset:true};
  applySnapshot({...options,source,version:1,root:{id:'r',label:'',children:[]}},{resetView:true});
  const wait=()=>new Promise(resolve=>setTimeout(resolve,150));
  const assert=(value,message)=>{if(!value)throw new Error(message)};
  await wait();
  const page=document.querySelector('#markdown-page'),side=document.querySelector('#sidebar');
  const buttons=()=>page.querySelectorAll('button[aria-label="放大代码块"]');
  const original=markdown.currentSource(),scroll=markdown.editable.scrollTop;
  const sidebarBounds=side.getBoundingClientRect(),bounds=page.getBoundingClientRect();
  assert(buttons().length===1,'Only the mixed-case Mermaid block should have a button');
  assert(!buttons()[0].closest('[title]'),'Expand button must have no hover tooltip');
  const buttonBounds=buttons()[0].getBoundingClientRect();
  const language=markdown.editable.querySelectorAll('[data-type="code-block-info"]')[1].getBoundingClientRect();
  assert(buttonBounds.right<=language.left&&Math.abs(buttonBounds.top-language.top)<2,'Button placement');
  const block=markdown.editable.querySelectorAll('[data-type="code-block"]')[1];
  assert(block.dataset.mermaidPreview==='ready'&&getComputedStyle(block,'::before').backgroundImage.includes('blob:'),'Inline diagram missing');
  assert(block.querySelector('pre code').getClientRects().length===0,'Rendered Mermaid source occupies space');
  assert(markdown.editable.querySelector('pre code').getBoundingClientRect().height>0,'Ordinary code hidden');
  assert(markdown.currentSource()===source,'Rendering changed Markdown');
  buttons()[0].click();await wait();
  const viewer=page.querySelector('.markdown-code-viewer'),box=viewer.getBoundingClientRect();
  assert(box.width>0&&Math.abs(box.width-bounds.width)<2&&Math.abs(box.height-bounds.height)<2&&box.left>=sidebarBounds.right-1,'Viewer must fill only the canvas');
  const diagram=viewer.querySelector('.markdown-mermaid-expanded');
  assert(diagram?.complete&&diagram.naturalWidth>0,'WebKit could not display the SVG');
  const imageBounds=diagram.getBoundingClientRect(),sourceBounds=viewer.querySelector('pre').getBoundingClientRect();
  assert(sourceBounds.width>0&&imageBounds.right<=sourceBounds.left&&Math.abs(imageBounds.width/sourceBounds.width-3)<0.05,'Expected 3:1 diagram and source columns');
  assert(imageBounds.top===sourceBounds.top&&imageBounds.bottom===sourceBounds.bottom&&sourceBounds.right<=box.right,'Panes must share the available height and fit inside the viewer');
  const divider=viewer.querySelector('[role="separator"]');
  let captured=null;
  divider.setPointerCapture=id=>captured=id;
  divider.hasPointerCapture=id=>captured===id;
  divider.releasePointerCapture=()=>captured=null;
  const drag=(type,x)=>divider.dispatchEvent(new PointerEvent(type,{pointerId:1,isPrimary:true,clientX:x,bubbles:true}));
  const checkShare=expected=>{
    const left=diagram.getBoundingClientRect().width,right=viewer.querySelector('pre').getBoundingClientRect().width;
    assert(Math.abs(100*left/(left+right)-expected)<0.2,'Unexpected diagram width at '+expected+'%');
  };
  drag('pointerdown',imageBounds.right+5);
  drag('pointermove',box.left-box.width);checkShare(15);
  drag('pointermove',box.right+box.width);checkShare(85);
  drag('pointerup',box.right);drag('pointermove',box.left);checkShare(85);
  divider.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}));checkShare(84);
  assert(side.getBoundingClientRect().width===sidebarBounds.width,'Sidebar resized');
  assert(viewer.querySelector('code').textContent.includes('A --> B')&&!viewer.textContent.includes('const first'),'Wrong block');
  viewer.querySelector('button').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  assert(viewer.hidden&&!markdown.editable.inert&&markdown.currentSource()===original&&markdown.editable.scrollTop===scroll,'Esc must restore document');
  buttons()[0].click();viewer.querySelector('button').click();
  assert(viewer.hidden,'Collapse button failed');
  await toggleSource(true);
  assert(document.querySelector('#source-editor').value===source,'Original Mermaid source missing in source mode');
  await toggleSource(false);await wait();
  const field=markdown.editable.querySelectorAll('[data-type="code-block-info"]')[1];
  for(const [language,count] of [['mermaidx',0],['MERMAID',1],['',0],['mermaid',1]]){
    field.textContent=language;await wait();
    assert(buttons().length===count,'Unexpected button count for '+language);
  }
  const body=block.querySelector('pre code');
  body.textContent='invalid diagram';await wait();
  assert(block.dataset.mermaidPreview==='error'&&body.textContent==='invalid diagram'&&body.getBoundingClientRect().height>0,'Invalid source lost');
  body.textContent='sequenceDiagram\nAlice->>Bob: Hello';await wait();
  assert(block.dataset.mermaidPreview==='ready','Diagram did not recover after editing');
  buttons()[0].click();markdown.load('另一篇文档', {...options,path:'另一篇.md'});
  assert(viewer.hidden&&!markdown.editable.inert,'Viewer survived document switch');
  window.webkit.messageHandlers.result.postMessage({passed:true,message:'PASS: code viewer placement, sidebar, language changes, dismissal and document switch'});
}catch(error){window.webkit.messageHandlers.result.postMessage({passed:false,message:error.message})}
